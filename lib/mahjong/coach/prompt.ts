/**
 * LLM へのプロンプト。サーバ側で組み立て、クライアントからは事実シートだけ受け取る。
 */
import type { CoachKind } from "./facts";

export const COACH_KINDS: readonly CoachKind[] = ["win", "discard", "read"];

export const MAX_FACT_LINES = 80;
export const MAX_FACT_LINE_LENGTH = 400;

const SYSTEM = [
  "あなたは学生麻雀（学生麻雀連盟ルール）を教える、親切で正確な麻雀コーチです。",
  "必ず日本語で、麻雀を覚えたての学生にも分かる言葉で説明してください。",
  "重要: 説明の根拠は、ユーザーが渡す「事実シート」だけです。",
  "事実シートにない役・符・点数・枚数・牌を作ったり、計算し直したりしてはいけません。",
  "事実シートの数値と矛盾することを書いてはいけません。分からないことは分からないと書いてください。",
  "事実シートに理由が書かれていないことは、推測で理由を作らずに事実だけを述べてください。",
  "Markdown の見出しは使わず、短い段落と箇条書きで書いてください。",
].join("\n");

const TASK: Record<CoachKind, string> = {
  win: [
    "この和了を解説してください。",
    "1. 成立した役ごとに、なぜ成立したかを面子構成や待ちと結びつけて1文ずつ。",
    "2. 符の計算を内訳の順に説明（役満の場合は省略）。",
    "3. 最後に点数と支払いを1文で。",
    "全体で250字程度。",
  ].join("\n"),
  discard: [
    "この局面で何を切るべきかを解説してください。",
    "1. コードの推奨打牌がなぜ良いのかを、向聴数と受け入れ枚数（どの牌が何枚）を使って説明。",
    "   向聴数の意味は事実シートの説明に従うこと（2向聴以上を「和了に近い」と書かない）。",
    "2. 2番目の候補と比べて何が違うかを1〜2文で。",
    "3. 立直している相手がいる場合は、危険度にも触れる。",
    "全体で200字程度。",
  ].join("\n"),
  read: [
    "この相手の河から、待ちや手の方向性を読む方法を解説してください。",
    "1. まず「確定情報（現物）」と「推測（筋・壁・宣言牌・色の偏り）」をはっきり区別する。",
    "2. 推測は断定せず「〜の可能性がある」と書く。「比較的安全な牌」と「注意が必要な牌」を取り違えないこと。",
    "3. 最後に、自分の手牌から切るならどれが比較的安全かを、安全度の数値を根拠に1〜2文で。",
    "全体で250字程度。",
  ].join("\n"),
};

export function buildMessages(kind: CoachKind, lines: string[]) {
  return [
    { role: "system", content: SYSTEM },
    { role: "user", content: `${TASK[kind]}\n\n【事実シート】\n${lines.join("\n")}` },
  ];
}
